#!/usr/bin/env python3
"""
Generate rtl/crc32_d512.v : CRC-32 (IEEE 802.3, reflected, poly 0xEDB88320)
that consumes ONE 512-bit (64-byte) beat per clock.

    crc_next = A * crc  XOR  B * data        (all arithmetic over GF(2))

Byte order matches the Stage-1 design: byte j of the beat is data[8j +: 8],
byte 0 enters the CRC first.  Init (0xFFFFFFFF) and final XOR are NOT part
of this block - the packetizer handles them.
"""
import random, zlib, sys

DATA_BITS = 512
POLY_R = 0xEDB88320

def crc_bytes(state, bs):
    """Byte-serial reflected CRC update, no init / no final xor."""
    for b in bs:
        state ^= b
        for _ in range(8):
            state = (state >> 1) ^ POLY_R if state & 1 else state >> 1
    return state

def beat_bytes(data):                       # 512-bit int -> 64 bytes, byte0 = LSB
    return [(data >> (8 * j)) & 0xFF for j in range(DATA_BITS // 8)]

def update(state, data):
    return crc_bytes(state, beat_bytes(data))

# ---- Linearity: build the A (32x32) and B (32x512) matrices ----------------
# Column k of a matrix = response to a single-bit input k.
# update(0, 0) == 0, so update(s, d) = update(s, 0) ^ update(0, d).
col_A = [update(1 << k, 0) for k in range(32)]
col_B = [update(0, 1 << k) for k in range(DATA_BITS)]

# Row masks: maskS[i] bit k = 1  <=>  state[k] contributes to crc_next[i]
maskS = [sum(((col_A[k] >> i) & 1) << k for k in range(32)) for i in range(32)]
maskD = [sum(((col_B[k] >> i) & 1) << k for k in range(DATA_BITS)) for i in range(32)]

def apply_masks(state, data):
    out = 0
    for i in range(32):
        bit = (bin(state & maskS[i]).count("1") + bin(data & maskD[i]).count("1")) & 1
        out |= bit << i
    return out

# ---- Self-check against zlib (the independent reference) -------------------
random.seed(1)
for _ in range(200):
    flit = bytes(random.getrandbits(8) for _ in range(256))
    s = 0xFFFFFFFF
    for k in range(4):                                  # 4 beats per FLIT
        beat = int.from_bytes(flit[64 * k:64 * k + 64], "little")
        s = apply_masks(s, beat)
    assert (s ^ 0xFFFFFFFF) == zlib.crc32(flit), "MISMATCH vs zlib"
print("python self-check: mask model == zlib.crc32 on 200 random FLITs  OK")

# ---- Zero-skip: feeding k all-zero beats == multiplying the CRC state by A^k ----
def zero_beats(state, k):
    for _ in range(k):
        state = apply_masks(state, 0)
    return state

def zmask(k):                                     # row masks of A^k (32x32)
    cols = [zero_beats(1 << c, k) for c in range(32)]
    return [sum(((cols[c] >> i) & 1) << c for c in range(32)) for i in range(32)]
ZM = {k: zmask(k) for k in (1, 2, 3)}

def skip_model(state, k):
    out = 0
    for i in range(32):
        out |= (bin(state & ZM[k][i]).count("1") & 1) << i
    return out

# self-check: early-TLAST FLIT (w+1 real beats, 3-w zero beats) == zlib on padded FLIT
for _ in range(300):
    w = random.randint(0, 2)
    flit = bytes(random.getrandbits(8) for _ in range(64 * (w + 1))) + bytes(64 * (3 - w))
    s_ = 0xFFFFFFFF
    for k in range(w + 1):
        s_ = apply_masks(s_, int.from_bytes(flit[64*k:64*k+64], "little"))
    s_ = skip_model(s_, 3 - w)
    assert (s_ ^ 0xFFFFFFFF) == zlib.crc32(flit), "ZERO-SKIP MISMATCH"
print("python self-check: zero-skip (A^k) == zlib.crc32 on 300 partial FLITs  OK")

# ---- Emit Verilog -----------------------------------------------------------
L = []
L.append("// AUTO-GENERATED by scripts/gen_crc.py - do not edit by hand.")
L.append("// CRC-32 (IEEE 802.3, reflected) over one 512-bit beat per clock.")
L.append("//   crc_next = A*crc_in ^ B*data   (GF(2) matrix form)")
L.append("// No init / final-xor here: caller seeds 32'hFFFFFFFF and inverts the result.")
L.append("module crc32_d512 (")
L.append("    input  [31:0]  crc_in,")
L.append("    input  [511:0] data,")
L.append("    output [31:0]  crc_out")
L.append(");")
for i in range(32):
    L.append(f"    localparam [31:0]  MS{i:02d} = 32'h{maskS[i]:08X};")
for i in range(32):
    L.append(f"    localparam [511:0] MD{i:02d} = 512'h{maskD[i]:0128X};")
for i in range(32):
    L.append(f"    assign crc_out[{i}] = ^(crc_in & MS{i:02d}) ^ ^(data & MD{i:02d});")
L.append("endmodule")
L.append("")
L.append("// Skip k all-zero 512-bit beats in one step: crc_out = A^k * crc_in   (k = 1..3)")
L.append("module crc32_zero_skip (")
L.append("    input  [31:0] crc_in,")
L.append("    input  [1:0]  k,          // number of zero beats to skip (1..3)")
L.append("    output [31:0] crc_out")
L.append(");")
for kk in (1, 2, 3):
    for i in range(32):
        L.append(f"    localparam [31:0] Z{kk}M{i:02d} = 32'h{ZM[kk][i]:08X};")
    L.append(f"    wire [31:0] y{kk};")
    for i in range(32):
        L.append(f"    assign y{kk}[{i}] = ^(crc_in & Z{kk}M{i:02d});")
L.append("    assign crc_out = (k == 2'd1) ? y1 : (k == 2'd2) ? y2 : (k == 2'd3) ? y3 : crc_in;")
L.append("endmodule")

# ---------------------------------------------------------------------------
# crc32_meta_272 : IEEE CRC-32 (init/final-xor FFFFFFFF) over the 272-bit (34-byte)
# framing metadata, flattened into a GF(2) matrix (balanced XOR tree per output
# bit) instead of the original bit-serial `always @*` loop (a ~272-step
# mux/XOR chain after elaboration).
#   crc = ~update(FFFFFFFF, bytes) = (B*data) ^ K,   K = ~update(FFFFFFFF, 34 zero bytes)
# ---------------------------------------------------------------------------
META_BITS = 272
META_BYTES = META_BITS // 8
def meta_update(state, data):
    return crc_bytes(state, [(data >> (8 * j)) & 0xFF for j in range(META_BYTES)])
colM = [meta_update(0, 1 << k) for k in range(META_BITS)]
maskM = [sum(((colM[k] >> i) & 1) << k for k in range(META_BITS)) for i in range(32)]
KM = meta_update(0xFFFFFFFF, 0) ^ 0xFFFFFFFF
def meta_model(data):
    out = 0
    for i in range(32):
        out |= ((bin(data & maskM[i]).count("1") & 1) ^ ((KM >> i) & 1)) << i
    return out
for _ in range(500):
    d = random.getrandbits(META_BITS)
    assert meta_model(d) == zlib.crc32(d.to_bytes(META_BYTES, "little")), "META CRC MISMATCH vs zlib"
print("python self-check: flat meta-CRC matrix == zlib.crc32 on 500 random 34-byte fields  OK")
M = []
M.append("// AUTO-GENERATED by scripts/gen_crc.py - do not edit by hand.")
M.append("// IEEE CRC-32 (reflected poly 0xEDB88320, init/final-xor 0xFFFFFFFF) over a 272-bit")
M.append("// metadata field, bytes consumed low-to-high.  Same function as the original")
M.append("// bit-serial loop, but expressed as 32 parity (XOR-tree) equations so synthesis")
M.append("// sees a log2-depth network instead of a ~272-step sequential mux/XOR chain.")
M.append("// Verified against zlib.crc32 by gen_crc.py and by tb/tb_crc_equiv.v.")
M.append("module crc32_meta_272 (")
M.append("    input  [271:0] data,")
M.append("    output [31:0]  crc")
M.append(");")
for i in range(32):
    M.append(f"    localparam [271:0] MM{i:02d} = 272'h{maskM[i]:068X};")
for i in range(32):
    M.append(f"    assign crc[{i}] = (^(data & MM{i:02d})) ^ 1'b{(KM >> i) & 1};")
M.append("endmodule")
open("rtl/crc32_meta_272.v", "w").write("\n".join(M) + "\n")
print("wrote rtl/crc32_meta_272.v; meta XOR fan-in max", max(bin(m).count("1") for m in maskM))

open("rtl/crc32_d512.v", "w").write("\n".join(L) + "\n")

fan = [bin(maskS[i]).count("1") + bin(maskD[i]).count("1") for i in range(32)]
print(f"XOR fan-in per output bit: min {min(fan)}, max {max(fan)}  "
      f"-> XOR2 depth ~ {max(fan).bit_length()}")
print("wrote rtl/crc32_d512.v")
